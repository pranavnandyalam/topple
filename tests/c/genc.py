"""Generate the C header of a first-party ``topple.policy/1`` graph (docs/design/phase-2.md §3.2,
§6 ``test_c_reference``).

``python tests/c/genc.py POLICY.onnx --out policy.h`` validates the bytes as the loader does
(``validate_policy_bytes``: canonical, finite float32 tensors), then requires one of the two §3.2
sequences (``structure_match``: ``clip(mean)`` for PPO, ``tanh(mean)`` for SAC) and reads the twelve
initializers **by position** in that sequence, as the Phase 8 C path will: ``mean``, ``inv_std``,
``lo``, ``hi``, ``W0``, ``b0``, ``W1``, ``b1``, ``W2``, ``b2``, ``act_lo``, ``act_hi``. Every value
is written as a ``float.hex`` literal (exact: a float32 widened to a double and back is the same
number), with the policy's sha256. Anything else is refused with exit 2 and one line on stderr.

Tensors are read from ``raw_data`` with ``numpy.frombuffer`` (never ``numpy_helper``), and the only
ONNX entry point is ``ModelProto.FromString``.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from collections.abc import Sequence
from pathlib import Path

import numpy as np
import numpy.typing as npt
import onnx

from topple._inputs import open_regular
from topple.policy.validate import ValidatedPolicy, structure_match, validate_policy_bytes

MAX_BYTES = 1 << 20  # MAX_ONNX_BYTES
NAMES = (
    "MEAN",
    "INV_STD",
    "OBS_LO",
    "OBS_HI",
    "W0",
    "B0",
    "W1",
    "B1",
    "W2",
    "B2",
    "ACT_LO",
    "ACT_HI",
)
"""The §3.2 initializers in position order (first use: node index, then input position)."""
PER_LINE = 4


class RefusedError(Exception):
    """The file is not a first-party §3.2 policy this generator can read by position."""


def _width(info: onnx.ValueInfoProto) -> int:
    dims = info.type.tensor_type.shape.dim
    if len(dims) != 2 or dims[1].WhichOneof("value") != "dim_value":
        raise RefusedError("the input and output need a static width")
    width: int = dims[1].dim_value
    return width


def _validated(data: bytes) -> ValidatedPolicy:
    try:
        proto: onnx.ModelProto = onnx.ModelProto.FromString(data)
        d, a = _width(proto.graph.input[0]), _width(proto.graph.output[0])
    except RefusedError:
        raise
    except Exception:  # DecodeError, a missing input or output, ...
        raise RefusedError("not a policy graph (onnx_parse_failed)") from None
    result = validate_policy_bytes(data, d, a)
    if isinstance(result, list):
        raise RefusedError(f"the loader would refuse it: {result[0]}")
    return result


def positional_initializers(proto: onnx.ModelProto) -> list[npt.NDArray[np.float32]]:
    """The initializers in the order the §3.2 sequence first uses them, as float32 arrays."""
    tensors = {t.name: t for t in proto.graph.initializer}
    order: list[str] = []
    for node in proto.graph.node:
        order += [name for name in node.input if name in tensors and name not in order]
    if len(order) != len(NAMES):
        raise RefusedError(f"{len(order)} initializers, not {len(NAMES)}")
    arrays = []
    for name in order:
        t = tensors[name]
        arr = np.frombuffer(t.raw_data, dtype="<f4").reshape(tuple(t.dims))
        if not np.isfinite(arr).all():
            raise RefusedError(f"initializer {name} is not finite")
        arrays.append(arr.astype(np.float32))
    return arrays


def _literal(value: float) -> str:
    return f"{float(value).hex()}f"


def _array(name: str, values: npt.NDArray[np.float32], size: str) -> list[str]:
    flat = [_literal(v) for v in values.reshape(-1)]
    rows = [", ".join(flat[i : i + PER_LINE]) for i in range(0, len(flat), PER_LINE)]
    return [f"static const float {name}[{size}] = {{", *(f"    {r}," for r in rows), "};"]


def header(data: bytes) -> str:
    """The C header for the policy bytes ``data``; ``RefusedError`` for anything but a valid,
    canonical first-party §3.2 sequence."""
    if len(data) > MAX_BYTES:
        raise RefusedError(f"more than {MAX_BYTES} bytes")
    validated = _validated(data)
    proto: onnx.ModelProto = onnx.ModelProto.FromString(validated.canonical)
    rule = structure_match(proto)
    if rule == "other":
        raise RefusedError("not a first-party sequence (structure_match: other)")
    values = dict(zip(NAMES, positional_initializers(proto), strict=True))
    h1, d = values["W0"].shape
    h2 = values["W1"].shape[0]
    a = values["W2"].shape[0]
    sha = hashlib.sha256(data).hexdigest()
    lines = [
        "/* Generated by tests/c/genc.py from policy.onnx: do not edit. */",
        f'#define POLICY_SHA256 "{sha}"',
        f"#define POLICY_D {d}",
        f"#define POLICY_H1 {h1}",
        f"#define POLICY_H2 {h2}",
        f"#define POLICY_A {a}",
        f"#define POLICY_SAC {int(rule == 'tanh(mean)')} /* {rule} */",
    ]
    sizes = {
        "MEAN": "POLICY_D",
        "INV_STD": "POLICY_D",
        "W0": "POLICY_H1 * POLICY_D",
        "B0": "POLICY_H1",
        "W1": "POLICY_H2 * POLICY_H1",
        "B1": "POLICY_H2",
        "W2": "POLICY_A * POLICY_H2",
        "B2": "POLICY_A",
    }
    for name in NAMES:
        if name in sizes:
            lines += _array(name, values[name], sizes[name])
        else:  # a rank-0 Clip bound
            lines.append(f"static const float {name} = {_literal(values[name].item())};")
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the C header of a policy.onnx.")
    parser.add_argument("policy", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        fh, _ = open_regular(args.policy, MAX_BYTES)  # never blocks on a FIFO
        with fh:
            data = fh.read(MAX_BYTES + 1)
        text = header(data)
    except (OSError, ValueError, RefusedError) as exc:
        detail = exc.strerror if isinstance(exc, OSError) else str(exc)
        print(f"genc: {args.policy.name}: {detail}", file=sys.stderr)
        return 2
    args.out.write_text(text, encoding="ascii")
    return 0


if __name__ == "__main__":
    sys.exit(main())
